"""Generates engine/src/tables/generated.rs from the oracle's --dump-tables.

Every table keeps the row order the C++ holds it in, because the C++ looks rows
up by binary search over that order (IndexedArray, std::map), and the port
does the same. The engine's table test re-dumps the generated tables in the
oracle's format and compares them with corpus/golden/tables.txt.

Usage: python -I gen_tables.py <tables.txt> <generated.rs>
"""

import sys
from pathlib import Path


def units(field):
    assert field.startswith("[") and field.endswith("]"), field
    inner = field[1:-1]
    return [int(x, 16) for x in inner.split(" ")] if inner else []


def text(field):
    codes = units(field)
    assert all(not (0xD800 <= c < 0xE000) for c in codes), field
    return "".join(chr(c) for c in codes)


def lit(value):
    out = []
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{code:x}}}")
    return '"' + "".join(out) + '"'


def num(value):
    v = float(value)
    if v != v or v in (float("inf"), float("-inf")):
        raise ValueError(value)
    return value if any(c in value for c in ".en") else value + ".0"


def char_font(fields):
    if fields[0] == "null":
        return "None"
    return f"Some(CharFont {{ chr: {fields[0]}, font: {fields[1]}, bold_font: {fields[2]} }})"


def main():
    source, target = sys.argv[1], sys.argv[2]
    lines = Path(source).read_text(encoding="utf-8").splitlines()
    names = []
    fonts = []
    current = None
    rows = {}
    sections = {key: [] for key in (
        "textstyle-default", "textstyle", "symfont", "param", "general",
        "symbol", "formula", "fsym", "fsymtext", "fsymformula", "macro",
        "newcmd-code", "newcmd-repl", "color", "unit", "glue", "gluetable",
        "supmap", "submap", "unparsed", "block")}
    for line in lines:
        tag, _, rest = line.partition(" ")
        fields = rest.split(" ")
        if tag == "fontname":
            names.append(fields[1])
        elif tag == "font":
            current = {"id": int(fields[0]), "fields": fields[1:]}
            fonts.append(current)
            rows[current["id"]] = {"metric": [], "ext": [], "larger": [], "lig": [], "kern": []}
        elif tag in ("metric", "ext", "larger", "lig", "kern"):
            rows[int(fields[0])][tag].append(fields[1:])
        else:
            sections[tag].append(rest)

    out = []
    w = out.append
    w("// Generated by tools/gen_tables.py from corpus/golden/tables.txt.")
    w("// Do not edit: change the generator or regenerate from the oracle.")
    w("")
    w("use super::{CharFont, FontInfo, MacroKind, MacroInfo, Symbol, TextStyle};")
    w("")
    w(f"pub static FONT_NAMES: [&str; {len(names)}] = [")
    for name in names:
        w(f"    {lit(name)},")
    w("];")
    w("")
    for font in fonts:
        fid = font["id"]
        r = rows[fid]
        w(f"static METRICS_{fid}: [[f32; 5]; {len(r['metric'])}] = [")
        for m in r["metric"]:
            w("    [" + ", ".join(num(x) for x in m) + "],")
        w("];")
        w(f"static EXTENSIONS_{fid}: [[i32; 5]; {len(r['ext'])}] = [")
        for m in r["ext"]:
            w("    [" + ", ".join(m) + "],")
        w("];")
        w(f"static LARGERS_{fid}: [[i32; 3]; {len(r['larger'])}] = [")
        for m in r["larger"]:
            w("    [" + ", ".join(m) + "],")
        w("];")
        w(f"static LIGATURES_{fid}: [[u16; 3]; {len(r['lig'])}] = [")
        for m in r["lig"]:
            w("    [" + ", ".join(m) + "],")
        w("];")
        w(f"static KERNS_{fid}: [[f32; 3]; {len(r['kern'])}] = [")
        for m in r["kern"]:
            w("    [" + ", ".join(num(x) for x in m) + "],")
        w("];")
    w("")
    w(f"pub static FONTS: [FontInfo; {len(fonts)}] = [")
    for font in fonts:
        fid = font["id"]
        path, xh, space, quad, skew, bold, roman, ss, tt, it = font["fields"]
        w("    FontInfo {")
        w(f"        path: {lit(path)},")
        w(f"        x_height: {num(xh)},")
        w(f"        space: {num(space)},")
        w(f"        quad: {num(quad)},")
        w(f"        skew_char: {skew},")
        w(f"        bold: {bold},")
        w(f"        roman: {roman},")
        w(f"        ss: {ss},")
        w(f"        tt: {tt},")
        w(f"        it: {it},")
        w(f"        metrics: &METRICS_{fid},")
        w(f"        extensions: &EXTENSIONS_{fid},")
        w(f"        largers: &LARGERS_{fid},")
        w(f"        ligatures: &LIGATURES_{fid},")
        w(f"        kerns: &KERNS_{fid},")
        w("    },")
    w("];")
    w("")

    defaults = sorted(sections["textstyle-default"], key=lambda s: int(s.split(" ")[0]))
    w("pub static TEXT_STYLE_DEFAULTS: [&str; 4] = [")
    for entry in defaults:
        w(f"    {lit(entry.split(' ', 1)[1])},")
    w("];")
    w("")
    styles = []
    for entry in sections["textstyle"]:
        name, index, *rest = entry.split(" ")
        if not styles or styles[-1][0] != name:
            styles.append((name, []))
        assert int(index) == len(styles[-1][1])
        styles[-1][1].append(char_font(rest))
    w(f"pub static TEXT_STYLES: [TextStyle; {len(styles)}] = [")
    for name, entries in styles:
        w(f"    TextStyle {{ name: {lit(name)}, fonts: &[" + ", ".join(entries) + "] },")
    w("];")
    w("")
    w(f"pub static SYMBOL_FONTS: [(&str, Option<CharFont>); {len(sections['symfont'])}] = [")
    for entry in sections["symfont"]:
        name, *rest = entry.split(" ")
        w(f"    ({lit(name)}, {char_font(rest)}),")
    w("];")
    w("")
    for tag, rust in (("param", "PARAMETERS"), ("general", "GENERAL_SETTINGS")):
        w(f"pub static {rust}: [(&str, f32); {len(sections[tag])}] = [")
        for entry in sections[tag]:
            name, value = entry.split(" ")
            w(f"    ({lit(name)}, {num(value)}),")
        w("];")
        w("")
    w(f"pub static SYMBOLS: [Symbol; {len(sections['symbol'])}] = [")
    for entry in sections["symbol"]:
        name, kind, limits, unicode = entry.split(" ")
        w(f"    Symbol {{ name: {lit(name)}, atom_type: {kind}, limits: {limits}, unicode: {unicode} }},")
    w("];")
    w("")
    w(f"pub static PREDEFINED_FORMULAS: [(&str, &str); {len(sections['formula'])}] = [")
    for entry in sections["formula"]:
        name, code = entry.split(" [", 1)
        w(f"    ({lit(text(name))}, {lit(text('[' + code))}),")
    w("];")
    w("")
    for tag, rust in (("fsym", "FORMULA_SYMBOL_MAPPINGS"),
                      ("fsymtext", "FORMULA_TEXT_MAPPINGS"),
                      ("fsymformula", "FORMULA_FORMULA_MAPPINGS")):
        w(f"pub static {rust}: [(i32, &str); {len(sections[tag])}] = [")
        for entry in sections[tag]:
            code, value = entry.split(" ", 1)
            w(f"    ({code}, {lit(text(value))}),")
        w("];")
        w("")
    w(f"pub static MACROS: [MacroInfo; {len(sections['macro'])}] = [")
    kinds = {"predef": "MacroKind::Predefined", "inflation": "MacroKind::Inflation", "other": "MacroKind::Other"}
    for entry in sections["macro"]:
        head, _, tail = entry.rpartition("] ")
        argc, opts, kind = tail.split(" ")
        w(f"    MacroInfo {{ name: {lit(text(head + ']'))}, argc: {argc}, pos_opts: {opts}, kind: {kinds[kind]} }},")
    w("];")
    w("")
    for tag, rust in (("newcmd-code", "NEW_COMMAND_CODES"), ("newcmd-repl", "NEW_COMMAND_REPLACEMENTS")):
        w(f"pub static {rust}: [(&str, &str); {len(sections[tag])}] = [")
        for entry in sections[tag]:
            name, code = entry.split(" [", 1)
            w(f"    ({lit(text(name))}, {lit(text('[' + code))}),")
        w("];")
        w("")
    w(f"pub static COLORS: [(&str, u32); {len(sections['color'])}] = [")
    for entry in sections["color"]:
        name, value = entry.split(" ")
        w(f"    ({lit(name)}, 0x{value}),")
    w("];")
    w("")
    w(f"pub static UNITS: [(&str, i8); {len(sections['unit'])}] = [")
    for entry in sections["unit"]:
        name, value = entry.split(" ")
        w(f"    ({lit(name)}, {value}),")
    w("];")
    w("")
    w(f"pub static GLUE_TYPES: [[u16; 3]; {len(sections['glue'])}] = [")
    for entry in sections["glue"]:
        w("    [" + ", ".join(entry.split(" ")[1:]) + "],")
    w("];")
    w("")
    w("pub static GLUE_TABLE: [[[i8; 5]; 8]; 8] = [")
    table = [[None] * 8 for _ in range(8)]
    for entry in sections["gluetable"]:
        l, r, *values = entry.split(" ")
        table[int(l)][int(r)] = values
    for l in range(8):
        w("    [")
        for r in range(8):
            w("        [" + ", ".join(table[l][r]) + "],")
        w("    ],")
    w("];")
    w("")
    for tag, rust in (("supmap", "SUP_SCRIPT_MAP"), ("submap", "SUB_SCRIPT_MAP")):
        w(f"pub static {rust}: [(u16, u8); {len(sections[tag])}] = [")
        for entry in sections[tag]:
            a, b = entry.split(" ")
            w(f"    ({a}, {b}),")
        w("];")
        w("")
    w(f"pub static UNPARSED_CONTENTS: [&str; {len(sections['unparsed'])}] = [")
    for entry in sections["unparsed"]:
        w(f"    {lit(text(entry))},")
    w("];")
    w("")
    w(f"pub static UNICODE_BLOCKS: [(u16, u16); {len(sections['block'])}] = [")
    for entry in sections["block"]:
        a, b = entry.split(" ")
        w(f"    ({a}, {b}),")
    w("];")

    Path(target).parent.mkdir(parents=True, exist_ok=True)
    Path(target).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(lines)} table lines -> {target}")


if __name__ == "__main__":
    main()
